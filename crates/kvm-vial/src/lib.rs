//! Vial support on the RP2354B (software.md §4.11): the keymap editor protocol and a QMK-style keymap engine for
//! keyboards that have no Vial of their own. Free of I/O, like `kvm-core`, which wires it into the engine.
//!
//! - **Matrix:** a keyboard without Vial only tells the KVM which HID usages are down, so the "matrix" is the
//!   keyboard page itself: position = usage 0x00–0xE7, row = usage / 8, column = usage % 8. 29 rows of one byte fit
//!   Vial's matrix tester into one 32-byte report.
//! - **Layout:** a full-size keyboard with ANSI/ISO options and a block of extra keys, generated by `build.rs`.
//!   Usages that are not in it (keypad extras 0xA5–0xDF) pass through unmapped.
//! - [`keymap`] holds layers, macros and settings and turns them into flash items; [`remap`] applies them to the
//!   keyboard state; [`protocol`] answers the Vial app.
//!
//! The keycode decoding ([`keycode`]) and the request handlers ([`protocol`]) are adapted from RMK
//! (<https://github.com/HaoboGu/rmk>, MIT, see `LICENSE-RMK-MIT`); the keymap engine is written for this state model.
#![cfg_attr(not(test), no_std)]

pub mod keycode;
pub mod keymap;
pub mod protocol;
pub mod remap;

pub use keymap::Keymap;
pub use protocol::{Context, Vial};
pub use remap::{Remap, Step};

pub const ROWS: usize = 29;
pub const COLS: usize = 8;
pub const POSITIONS: usize = ROWS * COLS;
pub const LAYERS: usize = 8;

include!(concat!(env!("OUT_DIR"), "/layout.rs"));

/// The keyboard definition Vial downloads, xz-compressed JSON (built by `build.rs`).
pub static DEFINITION: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/vial.json.xz"));

/// Identifies this definition to the Vial app (saved layouts are matched by it).
pub const KEYBOARD_UID: [u8; 8] = [0x9A, 0x2F, 0x6C, 0x41, 0xD3, 0x58, 0x0E, 0xB7];

/// Vial lists a raw HID interface only on a device whose serial number contains this.
pub const SERIAL_MAGIC: &str = "vial:f64c2b3c";

pub const REPORT_LEN: usize = 32;

/// QMK's raw HID interface: usage page 0xFF60, usage 0x61, 32-byte input and output reports, no report IDs.
pub const REPORT_DESC: &[u8] = &[
    0x06, 0x60, 0xFF, // Usage Page (0xFF60)
    0x09, 0x61, // Usage (0x61)
    0xA1, 0x01, // Collection (Application)
    0x09, 0x62, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x95, 0x20, 0x75, 0x08, 0x81, 0x02, // Input: 32 bytes
    0x09, 0x63, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x95, 0x20, 0x75, 0x08, 0x91, 0x02, // Output: 32 bytes
    0xC0, // End Collection
];

/// Whether position `pos` is a key of the Vial layout (and so goes through the keymap).
pub const fn in_layout(pos: u8) -> bool {
    (pos as usize) < POSITIONS && IN_LAYOUT[pos as usize / 32] & (1 << (pos % 32)) != 0
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Read;

    #[test]
    fn definition_unpacks_to_the_layout() {
        let mut json = String::new();
        xz2::read::XzDecoder::new(DEFINITION).read_to_string(&mut json).unwrap();
        assert!(json.starts_with("{\"name\":\"OpenDynKVM\""));
        assert!(json.contains("\"matrix\":{\"rows\":29,\"cols\":8}"));
        // ISO Enter (usage 0x28 = row 5, column 0) as layout option 0, choice 1.
        assert!(json.contains("\"5,0\\n\\n\\n0,1\""));
        assert!(DEFINITION.len() < json.len() / 2, "compressed {} of {}", DEFINITION.len(), json.len());
        // Letters, modifiers and F24 are keys; keypad extras and position 0 are not.
        assert!(in_layout(0x04) && in_layout(0xE7) && in_layout(0x73));
        assert!(!in_layout(0x00) && !in_layout(0xB0) && !in_layout(0xE8));
    }
}
