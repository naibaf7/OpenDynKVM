//! The mapping engine of the RP2354B (software.md §4.11): a QMK-style keymap engine for every input device, axis
//! rules, and the Vial protocol, through which the Vial app edits the keyboard part of a keymap. Free of I/O, like
//! `kvm-core`, which wires it into the engine.
//!
//! - **Positions:** the KVM only learns which controls are down, so the "matrix" is the controls themselves
//!   ([`pos`]): the keyboard page (position = usage 0x00–0xE7, row = usage / 8, column = usage % 8: 29 rows of one byte
//!   fit Vial's matrix tester into one 32-byte report), then mouse buttons, gamepad buttons and its hat, axis
//!   directions and the wheel as buttons. Vial sees the keyboard part only ([`KEYBOARD`]).
//! - **Keymaps:** four ([`KEYMAPS`]); each profile uses one of them or none (then input takes the short path through
//!   `kvm-core`).
//! - **Layout:** a full-size keyboard with ANSI/ISO options and a block of extra keys, generated by `build.rs`.
//!   Usages that are not in it (keypad extras 0xA5–0xDF) pass through unmapped.
//! - [`keymap`] holds layers, macros and settings and turns them into flash items; [`remap`] applies them to the
//!   controls; [`protocol`] answers the Vial app; [`macros`] reads and writes macros as steps for the host software.
//!
//! The keycode decoding ([`keycode`]) and the request handlers ([`protocol`]) are adapted from RMK
//! (<https://github.com/HaoboGu/rmk>, MIT, see `LICENSE-RMK-MIT`); the keymap engine is written for this state model.
#![cfg_attr(not(test), no_std)]

