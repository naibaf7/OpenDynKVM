/// Vial's matrix: the keyboard page.
pub const ROWS: usize = 29;
pub const COLS: usize = 8;
pub const KEYBOARD: usize = ROWS * COLS;
pub const LAYERS: usize = 8;
pub const KEYMAPS: usize = 4;

/// Where each kind of control starts in the position space, and how many there are.
pub mod pos {
    pub const MOUSE: u16 = crate::KEYBOARD as u16;
    pub const MOUSE_BUTTONS: u16 = 16;
    pub const PAD: u16 = MOUSE + MOUSE_BUTTONS;
    pub const PAD_BUTTONS: u16 = 32;
    /// The hat's directions: up, right, down, left.
    pub const HAT: u16 = PAD + PAD_BUTTONS;
    /// Axis directions as buttons (`axes::Target::Buttons`): two per axis input of [`crate::axes::INPUTS`] that has a
    /// centre (minus, then plus), one for each trigger.
    pub const AXIS: u16 = HAT + 4;
    pub const AXIS_BUTTONS: u16 = 2 * crate::axes::INPUTS as u16;
    pub const END: u16 = AXIS + AXIS_BUTTONS;
}

pub const POSITIONS: usize = pos::END as usize;
const WORDS: usize = POSITIONS.div_ceil(32);

/// A set of positions: the controls held down.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub struct PosSet([u32; WORDS]);

impl PosSet {
    pub const EMPTY: PosSet = PosSet([0; WORDS]);

    pub fn set(&mut self, p: u16, down: bool) {
        if (p as usize) < POSITIONS {
            let bit = 1 << (p % 32);
            if down {
                self.0[p as usize / 32] |= bit;
            } else {
                self.0[p as usize / 32] &= !bit;
            }
        }
    }

    pub fn has(&self, p: u16) -> bool {
        (p as usize) < POSITIONS && self.0[p as usize / 32] >> (p % 32) & 1 != 0
    }

    /// The keyboard part: the keys of `keys` below [`KEYBOARD`], modifiers included.
    pub fn from_keys(keys: &kvm_hid::KeyState) -> PosSet {
        let mut s = PosSet::EMPTY;
        for k in 0..KEYBOARD as u8 {
            if keys.is_pressed(k) {
                s.set(k as u16, true);
            }
        }
        s
    }

    /// Adds a mask of `n` controls starting at position `first` (bit i = control i).
    pub fn add_mask(&mut self, first: u16, mask: u32, n: u16) {
        for i in 0..n.min(32) {
            if mask >> i & 1 != 0 {
                self.set(first + i, true);
            }
        }
    }

    pub fn union(&self, o: &PosSet) -> PosSet {
        let mut s = *self;
        for (a, b) in s.0.iter_mut().zip(o.0) {
            *a |= b;
        }
        s
    }

    pub fn is_empty(&self) -> bool {
        self.0.iter().all(|w| *w == 0)
    }

    pub fn iter(&self) -> impl Iterator<Item = u16> + '_ {
        (0..POSITIONS as u16).filter(|p| self.has(*p))
    }
}

